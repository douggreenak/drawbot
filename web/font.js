/* Single-stroke ("plotter") font. Cap height = 6 units, y up, each glyph has width w
   and a list of strokes (polylines). Built from lines plus arc()/curve() helpers. */
(function (g) {
  const R = Math.PI / 180;

  /** Elliptical arc from angle a0 to a1 (degrees, CCW positive). */
  function arc(cx, cy, rx, ry, a0, a1, n) {
    n = n || Math.max(6, Math.ceil(Math.abs(a1 - a0) / 12));
    const p = [];
    for (let i = 0; i <= n; i++) {
      const a = (a0 + ((a1 - a0) * i) / n) * R;
      p.push([cx + rx * Math.cos(a), cy + ry * Math.sin(a)]);
    }
    return p;
  }

  /** Smooth Catmull-Rom spline through control points. */
  function curve(pts, seg) {
    seg = seg || 6;
    const out = [pts[0]];
    for (let i = 0; i < pts.length - 1; i++) {
      const p0 = pts[Math.max(0, i - 1)], p1 = pts[i], p2 = pts[i + 1], p3 = pts[Math.min(pts.length - 1, i + 2)];
      for (let s = 1; s <= seg; s++) {
        const t = s / seg, t2 = t * t, t3 = t2 * t;
        out.push([0, 1].map(k =>
          0.5 * (2 * p1[k] + (-p0[k] + p2[k]) * t + (2 * p0[k] - 5 * p1[k] + 4 * p2[k] - p3[k]) * t2 +
                 (-p0[k] + 3 * p1[k] - 3 * p2[k] + p3[k]) * t3)));
      }
    }
    return out;
  }

  const F = {};
  const def = (ch, w, strokes) => { F[ch] = { w, s: strokes }; };

  // ---- Letters -------------------------------------------------------------
  def('A', 4, [[[0, 0], [2, 6], [4, 0]], [[0.8, 2], [3.2, 2]]]);
  def('B', 4, [
    [[0, 6], [0, 0], [2.8, 0], ...arc(2.8, 1.5, 1.2, 1.5, -90, 90), [0, 3]],
    [[0, 6], [2.5, 6], ...arc(2.5, 4.5, 1.5, 1.5, 90, -90), [0, 3]]]);
  def('C', 4, [arc(2, 3, 2, 3, 45, 315)]);
  def('D', 4, [[[0, 0], [0, 6], [1.5, 6], ...arc(1.5, 3, 2.5, 3, 90, -90), [0, 0]]]);
  def('E', 4, [[[4, 6], [0, 6], [0, 0], [4, 0]], [[0, 3], [3, 3]]]);
  def('F', 4, [[[4, 6], [0, 6], [0, 0]], [[0, 3], [3, 3]]]);
  def('G', 4, [[...arc(2, 3, 2, 3, 45, 360), [2.3, 3]]]);
  def('H', 4, [[[0, 0], [0, 6]], [[4, 0], [4, 6]], [[0, 3], [4, 3]]]);
  def('I', 2, [[[1, 0], [1, 6]], [[0, 6], [2, 6]], [[0, 0], [2, 0]]]);
  def('J', 4, [[[4, 6], [4, 1.8], ...arc(2, 1.8, 2, 1.8, 0, -165)]]);
  def('K', 4, [[[0, 0], [0, 6]], [[4, 6], [0, 2.5]], [[1.2, 3.6], [4, 0]]]);
  def('L', 4, [[[0, 6], [0, 0], [4, 0]]]);
  def('M', 4, [[[0, 0], [0, 6], [2, 2.5], [4, 6], [4, 0]]]);
  def('N', 4, [[[0, 0], [0, 6], [4, 0], [4, 6]]]);
  def('O', 4, [arc(2, 3, 2, 3, 90, 450)]);
  def('P', 4, [[[0, 0], [0, 6], [2.5, 6], ...arc(2.5, 4.4, 1.5, 1.6, 90, -90), [0, 2.8]]]);
  def('Q', 4, [arc(2, 3, 2, 3, 90, 450), [[2.4, 1.7], [4, -0.5]]]);
  def('R', 4, [[[0, 0], [0, 6], [2.5, 6], ...arc(2.5, 4.4, 1.5, 1.6, 90, -90), [0, 2.8]], [[1.8, 2.8], [4, 0]]]);
  def('S', 4, [[...arc(2, 4.5, 1.9, 1.5, 30, 270), ...arc(2, 1.5, 2, 1.5, 90, -150)]]);
  def('T', 4, [[[0, 6], [4, 6]], [[2, 6], [2, 0]]]);
  def('U', 4, [[[0, 6], [0, 2], ...arc(2, 2, 2, 2, 180, 360), [4, 6]]]);
  def('V', 4, [[[0, 6], [2, 0], [4, 6]]]);
  def('W', 4, [[[0, 6], [1, 0], [2, 4], [3, 0], [4, 6]]]);
  def('X', 4, [[[0, 6], [4, 0]], [[4, 6], [0, 0]]]);
  def('Y', 4, [[[0, 6], [2, 3], [4, 6]], [[2, 3], [2, 0]]]);
  def('Z', 4, [[[0, 6], [4, 6], [0, 0], [4, 0]]]);

  // ---- Digits ----------------------------------------------------------------
  def('0', 3.5, [arc(1.75, 3, 1.75, 3, 90, 450), [[0.7, 1.2], [2.8, 4.8]]]);
  def('1', 3.5, [[[0.4, 4.7], [1.8, 6], [1.8, 0]]]);
  def('2', 3.5, [[...arc(1.75, 4.4, 1.6, 1.6, 160, -40), [0, 0], [3.5, 0]]]);
  def('3', 3.5, [[...arc(1.75, 4.5, 1.5, 1.5, 150, -90), ...arc(1.75, 1.5, 1.75, 1.5, 90, -150)]]);
  def('4', 3.5, [[[2.6, 0], [2.6, 6], [0, 1.8], [3.5, 1.8]]]);
  def('5', 3.5, [[[3.2, 6], [0.5, 6], [0.54, 3.53], ...arc(1.7, 2, 1.8, 2, 130, -140)]]);
  def('6', 3.5, [arc(1.75, 2, 1.75, 2, 0, 360), curve([[3.0, 5.7], [2.0, 6], [1.0, 5.3], [0.2, 3.8], [0, 2]])]);
  def('7', 3.5, [[[0, 6], [3.5, 6], [1.2, 0]]]);
  def('8', 3.5, [arc(1.75, 4.5, 1.5, 1.5, -90, 270), arc(1.75, 1.5, 1.75, 1.5, 90, 450)]);
  def('9', 3.5, [arc(1.75, 4, 1.75, 2, 0, 360), curve([[0.5, 0.3], [1.5, 0], [2.5, 0.7], [3.3, 2.2], [3.5, 4]])]);

  // ---- Punctuation & electrical symbols --------------------------------------
  def('-', 3, [[[0.2, 3], [2.8, 3]]]);
  def('+', 3.5, [[[0.3, 3], [3.2, 3]], [[1.75, 1.5], [1.75, 4.5]]]);
  def('=', 3.5, [[[0.3, 2.2], [3.2, 2.2]], [[0.3, 3.8], [3.2, 3.8]]]);
  def('.', 0.4, [[[0.2, 0], [0.2, 0.4]]]);
  def(',', 1, [[[0.6, 0.6], [0.2, -0.9]]]);
  def(':', 0.4, [[[0.2, 0.9], [0.2, 1.3]], [[0.2, 4.1], [0.2, 4.5]]]);
  def(';', 1, [[[0.6, 4.1], [0.6, 4.5]], [[0.6, 0.6], [0.2, -0.9]]]);
  def('_', 4, [[[0, -0.8], [4, -0.8]]]);
  def('/', 3, [[[0, 0], [3, 6]]]);
  def('\\', 3, [[[0, 6], [3, 0]]]);
  def('|', 0.4, [[[0.2, -1], [0.2, 6.5]]]);
  def('!', 0.4, [[[0.2, 6], [0.2, 2]], [[0.2, 0], [0.2, 0.4]]]);
  def('?', 3.5, [curve([[0, 4.8], [0.6, 5.8], [1.75, 6], [2.9, 5.6], [3.3, 4.6], [2.8, 3.6], [1.75, 2.9], [1.75, 2]]), [[1.75, 0], [1.75, 0.4]]]);
  def("'", 0.4, [[[0.2, 6], [0.2, 4.4]]]);
  def('"', 1.6, [[[0.2, 6], [0.2, 4.4]], [[1.4, 6], [1.4, 4.4]]]);
  def('*', 3, [[[0.3, 1.9], [2.7, 5.1]], [[0.3, 5.1], [2.7, 1.9]], [[1.5, 1.6], [1.5, 5.4]]]);
  def('#', 4, [[[1.2, 0], [1.8, 6]], [[2.4, 0], [3, 6]], [[0, 2], [4, 2]], [[0, 4], [4, 4]]]);
  def('<', 3, [[[3, 5], [0, 3], [3, 1]]]);
  def('>', 3, [[[0, 5], [3, 3], [0, 1]]]);
  def('(', 1.6, [curve([[1.4, 6.6], [0.4, 4.6], [0, 2.8], [0.4, 1], [1.4, -0.8]])]);
  def(')', 1.6, [curve([[0.2, 6.6], [1.2, 4.6], [1.6, 2.8], [1.2, 1], [0.2, -0.8]])]);
  def('[', 1.4, [[[1.4, 6.6], [0, 6.6], [0, -0.8], [1.4, -0.8]]]);
  def(']', 1.4, [[[0, 6.6], [1.4, 6.6], [1.4, -0.8], [0, -0.8]]]);
  def('%', 4, [arc(0.9, 5.0, 0.9, 0.9, 90, 450), arc(3.1, 1.0, 0.9, 0.9, 90, 450), [[0.2, 0], [3.8, 6]]]);
  def('&', 4, [curve([[4, 0], [1.4, 3.2], [0.4, 4.4], [1.2, 5.9], [2.2, 5.0], [1.6, 3.8], [0.4, 2.4], [0.2, 1.2], [1.2, 0], [2.4, 0.4], [4, 3]])]);
  def('@', 5, [arc(2.5, 3, 2.5, 3, 40, 400, 30).slice(0, 29), arc(2.4, 3, 0.9, 1.1, 0, 360)]);
  def('°', 1.8, [arc(0.9, 5.1, 0.9, 0.9, 90, 450)]);
  def('±', 3.5, [[[0.3, 3.6], [3.2, 3.6]], [[1.75, 2.1], [1.75, 5.1]], [[0.3, 0.6], [3.2, 0.6]]]);
  def('Ω', 4, [[[0, 0], [1.2, 0], ...arc(2, 3.3, 2, 2.7, 245, -65), [2.8, 0], [4, 0]]]);
  def('µ', 3, [[[0, 4], [0, -1.8]], [[0, 2], ...arc(1.5, 2, 1.5, 2, 180, 360), [3, 4]], [[3, 2], [3, 0.3], [3.4, 0]]]);
  def('~', 3.5, [curve([[0, 2.8], [0.9, 3.8], [1.75, 3], [2.6, 2.2], [3.5, 3.2]])]);
  def('^', 3, [[[0, 4], [1.5, 6], [3, 4]]]);

  g.DBFont = { glyphs: F, arc, curve, SPACE: 3, GAP: 1.5, CAP: 6 };
})(window);
